export type TranslationKey = keyof typeof dict["es"];

function interpolate(text: string, vars?: Record<string, string>): string {
  if (!vars) return text;
  return Object.entries(vars).reduce((acc, [key, value]) => acc.replaceAll(`{${key}}`, value), text);
}

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string>): string {
  const text = dict[lang][key] ?? dict.es[key] ?? key;
  return interpolate(text, vars);
}

// Masculino -> "m", femenino -> "f", No Binarie / No lo sé aún -> "n"
// (lenguaje neutro, ej. terminación en "e": "Segure", "Bienvenide").
function genderSuffix(pronoun: Pronoun | undefined): "m" | "f" | "n" {
  if (pronoun === "masculino") return "m";
  if (pronoun === "femenino") return "f";
  return "n";
}

// Hook principal: lee el idioma guardado en el perfil (por defecto "es") y
// devuelve una función `t(key, vars?)` para traducir. Cualquier pantalla
// puede usarlo sin pasar por un Provider — reutiliza el cache de useProfile.
export function useT() {
  const { data: profile } = useProfile();
  const lang: Language = profile?.language === "en" ? "en" : "es";
  const pronoun: Pronoun = profile?.pronoun ?? "no_se";
  const suffix = genderSuffix(pronoun);
  return {
    lang,
    pronoun,
    t: (key: TranslationKey, vars?: Record<string, string>) => translate(lang, key, vars),
    // Traduce una clave "de género": recibe la base sin sufijo (ej.
    // "welcome.greeting") y arma la clave real según el pronombre del perfil
    // (ej. "welcome.greeting.f"). La clave base + ".m"/".f"/".n" debe existir
    // en el diccionario.
    tg: (base: string, vars?: Record<string, string>) =>
      translate(lang, `${base}.${suffix}` as TranslationKey, vars),
  };
}
